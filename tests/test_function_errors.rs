//! Tests for function translation error cases.
//!
//! Verifies that PostgreSQL-specific functions that have no direct SQLite
//! equivalent produce clear, actionable error messages rather than silently
//! producing incorrect SQL.

use pg2sqlite::prelude::{Pg2Sqlite, Pg2SqliteOptions};

const SIMPLE_TABLE: &str = "CREATE TABLE t (id INT PRIMARY KEY, val INT, flag BOOLEAN);";

fn translate_err(sql: &str) -> String {
    Pg2Sqlite::default()
        .sql(sql)
        .unwrap()
        .translate(&Pg2SqliteOptions::default())
        .unwrap_err()
        .to_string()
}

fn translate_ok(sql: &str) -> String {
    let stmts =
        Pg2Sqlite::default().sql(sql).unwrap().translate(&Pg2SqliteOptions::default()).unwrap();
    stmts.iter().find(|s| matches!(s, sqlparser::ast::Statement::Query(_))).unwrap().to_string()
}

// ---------------------------------------------------------------------------
// ts_rank / ts_rank_cd
// ---------------------------------------------------------------------------

/// `ts_rank` has no direct SQLite equivalent.  The translator should fail
/// with a message that directs the user to FTS5's `bm25()`.
#[test]
fn test_ts_rank_causes_error() {
    let sql = "
        CREATE TABLE documents (id INTEGER PRIMARY KEY, content TEXT);
        SELECT ts_rank(content, 'query') FROM documents;
    ";
    let result = Pg2Sqlite::default().sql(sql).unwrap().translate(&Pg2SqliteOptions::default());

    assert!(result.is_err(), "ts_rank should produce a translation error");
    let error_msg = result.unwrap_err().to_string();
    assert!(
        error_msg.contains("bm25"),
        "Error should mention 'bm25' as the FTS5 alternative, got: {error_msg}"
    );
}

/// `ts_rank_cd` is subject to the same restriction as `ts_rank`.
